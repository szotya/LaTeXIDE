#!/usr/bin/env bash
set -euo pipefail
TASK_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$TASK_ROOT"
if [[ "$(uname -m)" != arm64 ]]; then echo 'Apple Silicon Mac is required.' >&2; exit 1; fi
bash scripts/cargo-local.sh build -p latexide-ffi -p latexide-mcp --locked --offline
# The archive is produced by Cargo, outside SwiftPM's target dependency graph.
# A content stamp forces a relink when only Rust changed.
python3 - <<'PY_STAMP'
from pathlib import Path
import hashlib
archive = Path('target/debug/liblatexide_ffi.a')
digest = hashlib.sha256(archive.read_bytes()).hexdigest()
stamp = Path('apps/macos/Sources/LaTeXIDEKit/CoreBuildIdentity.generated.swift')
content = '// Generated by scripts/build_macos.sh; no runtime developer path.\ninternal enum CoreBuildIdentity { static let archiveSHA256 = "' + digest + '" }\n'
if not stamp.exists() or stamp.read_text() != content:
    stamp.write_text(content)
PY_STAMP
export CLANG_MODULE_CACHE_PATH="$TASK_ROOT/.local/clang-module-cache"
SWIFT_FLAGS=(--package-path "$TASK_ROOT/apps/macos" --scratch-path "$TASK_ROOT/.local/swift-build" --cache-path "$TASK_ROOT/.local/swift-cache" --config-path "$TASK_ROOT/.local/swift-config" --security-path "$TASK_ROOT/.local/swift-security" --disable-sandbox)
swift build "${SWIFT_FLAGS[@]}" --product LaTeXIDE
TASK_BIN="$(swift build "${SWIFT_FLAGS[@]}" --show-bin-path)"
mkdir -p "$TASK_ROOT/dist" "$TASK_ROOT/.local"
TASK_STAGE="$(mktemp -d "$TASK_ROOT/.local/app-stage.XXXXXX")"
TASK_APP="$TASK_STAGE/LaTeXIDE.app"
TASK_CONTENTS="$TASK_APP/Contents"
mkdir -p "$TASK_CONTENTS/MacOS" "$TASK_CONTENTS/Resources" "$TASK_CONTENTS/Frameworks"
cp "$TASK_BIN/LaTeXIDE" "$TASK_CONTENTS/MacOS/LaTeXIDE"
cp apps/macos/Info.plist "$TASK_CONTENTS/Info.plist"
for TASK_RESOURCE_BUNDLE in "$TASK_BIN"/*.bundle; do
  if [[ -d "$TASK_RESOURCE_BUNDLE" ]]; then
    /usr/bin/ditto "$TASK_RESOURCE_BUNDLE" "$TASK_CONTENTS/Resources/$(basename "$TASK_RESOURCE_BUNDLE")"
  fi
done
if [[ ! -f "$TASK_CONTENTS/Resources/IDEThemeAssets_IDEThemeAssets.bundle/Contents/Resources/editor-themes.json" && ! -f "$TASK_CONTENTS/Resources/IDEThemeAssets_IDEThemeAssets.bundle/editor-themes.json" ]]; then
  echo 'Bundled IDE palettes are missing.' >&2; exit 1
fi
cp target/debug/latexide-mcp "$TASK_CONTENTS/Resources/latexide-mcp"
if [[ -d .local/texlive-macos ]]; then
  # Keep symlinks inside TeX Live intact; no developer-home path in the app.
  /usr/bin/rsync -a .local/texlive-macos/ "$TASK_CONTENTS/Resources/texlive/"
  # The no-documentation TeX profile leaves an unused dangling man-page alias.
  # Omit that alias from the app; codesign's resource verifier follows it.
  TASK_MAN_ALIAS="$TASK_CONTENTS/Resources/texlive/bin/universal-darwin/man"
  if [[ -L "$TASK_MAN_ALIAS" && ! -e "$TASK_MAN_ALIAS" ]]; then rm -- "$TASK_MAN_ALIAS"; fi
else
  echo 'Verified TeX Live runtime missing: see tools/texlive/README.md' >&2; exit 1
fi
codesign --force --sign - "$TASK_CONTENTS/Resources/latexide-mcp"
codesign --force --sign - "$TASK_APP"
codesign --verify --strict "$TASK_APP"
# Preserve the old inode while a previous GUI may still be mapped/running.
# Never truncate its executable in place, and retain a local rollback bundle.
if [[ -d "$TASK_ROOT/dist/LaTeXIDE.app" ]]; then
  TASK_PREVIOUS="$TASK_ROOT/dist/LaTeXIDE.previous.$(date +%Y%m%d-%H%M%S).$$.app"
  mv "$TASK_ROOT/dist/LaTeXIDE.app" "$TASK_PREVIOUS"
fi
mv "$TASK_APP" "$TASK_ROOT/dist/LaTeXIDE.app"
rmdir "$TASK_STAGE"
codesign --verify --strict "$TASK_ROOT/dist/LaTeXIDE.app"
echo "$TASK_ROOT/dist/LaTeXIDE.app"
